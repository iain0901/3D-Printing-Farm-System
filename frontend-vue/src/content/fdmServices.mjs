export function getAudience(id) {
  return audiences.find((item) => item.id === id) || null
}
export function getService(id) {
  return services.find((item) => item.id === id) || null
}
export function servicesForAudience(id) {
  return services.filter((item) => item.audience === id)
}
export function inquiryRoute(id) {
  return getService(id) ? { path: '/quote', query: { service: id, mode: 'estimate' } } : { path: '/quote' }
}
export function inquiryNotes(id) {
  const service = getService(id)
  if (!service) return ''
  return `【FDM 詢價｜${getAudience(service.audience).title}｜${service.title}】\n${service.brief}`
}
