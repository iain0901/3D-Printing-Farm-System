export function resolveSlicerHelp(label) {
  const normalized = String(label || '')
    .replace(/\s+/g, ' ')
    .trim()
  // Exact advanced names must win over broad basic-field matches such as “速度”.
  return slicerHelpTopics.find((t) => t.title === normalized) || slicerHelpTopics.find((t) => t.match.test(normalized)) || null
}
